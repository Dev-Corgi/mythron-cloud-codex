"""Export the card background at Duelyst sizes and the source UI glyphs.

Run from any directory: python build_assets.py
The original Duelyst sprite atlases are used directly by the card preview.
"""

from pathlib import Path
import json

from PIL import Image, ImageDraw, ImageFilter, ImageOps


ROOT = Path(__file__).resolve().parent
RESOURCES = ROOT.parents[1]
ICONS = ROOT / "icons"
SOURCES = ROOT / "sources"
ICONS.mkdir(exist_ok=True)


def export_card_frames() -> None:
    from frame_geometry import export
    export()


export_card_frames()


def crop_clean(source: Image.Image, box: tuple[int, int, int, int]) -> Image.Image:
    """Use a bounded cell and reject only almost invisible generated fringe."""
    rgba = source.convert("RGBA").crop(box)
    alpha = rgba.getchannel("A")
    visible = alpha.point(lambda value: 255 if value >= 32 else 0)
    bounds = visible.getbbox()
    if bounds is None:
        raise ValueError(f"empty icon cell: {box}")
    rgba = rgba.crop(bounds)
    rgba.putalpha(rgba.getchannel("A").point(lambda value: value if value >= 24 else 0))
    return rgba


def export_icon(image: Image.Image, destination: Path) -> None:
    """Fit each isolated icon on the same transparent 256px artboard."""
    scale = min(230 / image.width, 230 / image.height)
    width = round(image.width * scale)
    height = round(image.height * scale)
    resized = image.resize((width, height), Image.Resampling.LANCZOS)
    resized = resized.filter(ImageFilter.UnsharpMask(radius=0.7, percent=120, threshold=2))
    board = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    board.alpha_composite(resized, ((256 - width) // 2, (256 - height) // 2))
    board.save(destination)


sheet = Image.open(SOURCES / "ui_icons_generated.png").convert("RGBA")
cells = {
    "attack_melee": (110, 48, 372, 442),
    "health": (521, 112, 845, 428),
    "move_walk": (951, 111, 1263, 426),
    "range": (1337, 61, 1716, 433),
    "move_fly": (28, 490, 449, 841),
    "hourglass": (978, 502, 1242, 836),
}
for name, box in cells.items():
    export_icon(crop_clean(sheet, box), ICONS / f"{name}@2x.png")

attack_sheet = Image.open(SOURCES / "attack_types_generated.png").convert("RGBA")
midpoint = attack_sheet.width // 2
for name, box in (
    ("attack_ranged", (0, 0, midpoint, attack_sheet.height)),
    ("attack_area", (midpoint, 0, attack_sheet.width, attack_sheet.height)),
):
    export_icon(crop_clean(attack_sheet, box), ICONS / f"{name}@2x.png")
for name in ("attack_melee", "attack_ranged", "attack_area"):
    Image.open(ICONS / f"{name}@2x.png").resize(
        (128, 128), Image.Resampling.LANCZOS).save(ICONS / f"{name}.png")

ghost = Image.open(SOURCES / "move_phase_ghost_generated.png").convert("RGBA")
export_icon(crop_clean(ghost, (0, 0, ghost.width, ghost.height)), ICONS / "move_phase@2x.png")

# Every rarity shares the exact six-sided silhouette of the metal slot's face.
# Export real 1x/2x textures; no circular rarity texture or circular recess.
rarity_dir = ROOT / "rarity"
rarity_dir.mkdir(exist_ok=True)
rarity_sheet = Image.open(SOURCES / "rarity_hex_crystals.png").convert("RGBA")
for index, name in enumerate(("common", "rare", "epic", "legendary", "mythron")):
    left = round(index * rarity_sheet.width / 5)
    right = round((index + 1) * rarity_sheet.width / 5)
    gem = crop_clean(rarity_sheet, (left, 180, right, 500))
    # Align the solid crystal, excluding faint generated fringe/glow that
    # otherwise shifts the visible jewel within a nominally centered canvas.
    solid = gem.getchannel("A").point(lambda a: 255 if a >= 192 else 0).getbbox()
    gem = gem.crop(solid)
    gem = gem.resize((240, 104), Image.Resampling.LANCZOS)
    shape = Image.new("L", gem.size, 0)
    ImageDraw.Draw(shape).polygon(
        [(40, 0), (200, 0), (239, 52), (200, 103), (40, 103), (0, 52)], fill=255)
    shape.paste(ImageOps.mirror(shape.crop((0, 0, 120, 104))), (120, 0))
    gem.putalpha(shape)
    gem.resize((60, 26), Image.Resampling.LANCZOS).save(rarity_dir / f"{name}@2x.png")
    gem.resize((30, 13), Image.Resampling.LANCZOS).save(rarity_dir / f"{name}.png")

